def main():
    data = json.load(io.open(TARGET, encoding='utf-8'))
    added, skipped = 0, []
    for uid, spec in TABLES.items():
        entry = data.get(uid)
        if entry is None:
            skipped.append((uid, '대학 항목 없음'))
            continue
        if entry.get('conversion', {}).get('type'):
            skipped.append((uid, '이미 환산표 있음 — 덮어쓰지 않음'))
            continue
        entry['conversion'] = {
            'type': 'grade_table',
            'maxScore': None,
            'minScore': None,
            'perSubject': bool(spec['per_subject']),
            'gradeTable': bands(spec['rows']),
        }
        entry['comparativeGradeType'] = 'numeric_table'
        entry['conversionSource'] = spec['src']
        entry['conversionQuote'] = spec['quote']
        added += 1

    json.dump(data, io.open(TARGET, 'w', encoding='utf-8'), ensure_ascii=False)
    print('환산표 추가: %d개 대학' % added)
    for uid, why in skipped:
        print('  건너뜀 %s — %s' % (uid, why))
    return 0 if added else 1


if __name__ == '__main__':
    sys.exit(main())
