// ─── 맞춤 추천에서만 제외할 상위권 대학 ───────────────────────────────────
// 검정고시생이 현실적으로 지원하는 대학 위주로 추천되도록, 최상위권 대학은
// '맞춤 추천 / 추천 정렬(reco) / 합격 추천 결과(수시·정시)' 경로에서만 제외한다.
//
// 적용 범위
//   - O 적용: ResultsScreen 수시/정시 결과, ExploreScreen 추천순(reco) 정렬
//   - X 미적용: 전체 목록(가나다순), 대학 이름 검색 → 이 경로에는 그대로 노출
//
// 제외 사유
//   이 대학들은 일반학생 합격선(입결) 기준 데이터만 있어 검정고시 비교내신으로는
//   정확한 합격 예측이 사실상 불가하고, 실제 검정고시 합격 사례도 매우 드물다.
//   따라서 "현실적인 추천"의 신뢰도를 위해 추천 후보에서만 뺀다.
//
// 구성 (univId 기준, universities.json과 일치)
//   - SKY:   서울대 · 연세대 · 고려대
//   - 서성한: 서강대 · 성균관대 · 한양대 (본교)
//   - + 최상위권 인서울: 이화여대 · 중앙대 · 경희대 · 서울시립대 · 한국외대
//     (검정고시 합격선 데이터 부재 + 입결 최상위라 추천에서 함께 제외)
//
// 주의
//   - 본교 univId만 제외한다. 분교(연세대 미래, 고려대 세종, 한양대 ERICA 등)는
//     별도 univId라 영향을 받지 않는다.
//   - Set 멤버십(정확한 univId 일치)으로만 판정하므로 '남서울대' 등 이름이
//     겹치는 다른 대학은 제외되지 않는다.

export const TOP_TIER_EXCLUDE = new Set([
  'snu', // 서울대학교
  'yonsei', // 연세대학교
  'korea', // 고려대학교
  'sogang', // 서강대학교
  'skku', // 성균관대학교
  'hanyang', // 한양대학교
  'uA0000163', // 이화여자대학교
  'cau', // 중앙대학교
  'khu', // 경희대학교
  'uos', // 서울시립대학교
  'hufs', // 한국외국어대학교
]);

// 해당 univId가 추천에서 제외 대상인지
export function isTopTierExcluded(univId) {
  return TOP_TIER_EXCLUDE.has(univId);
}
